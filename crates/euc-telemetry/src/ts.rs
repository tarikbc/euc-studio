//! The schema as a TypeScript module for the studio front end.
//!
//! `cargo run -p euc-telemetry --example gen_ts` writes it to `app/src/engine/telemetry.gen.ts`;
//! a test fails when the committed file is stale.

use std::fmt::Write as _;

use crate::batch::{FLAG_POSES, HEADER_BYTES, MAGIC, POSE_FLOATS, VERSION};
use crate::schema::{CHANNELS, RateClass};

/// Path of the generated module, relative to the repository root.
pub const TS_PATH: &str = "app/src/engine/telemetry.gen.ts";

fn quote(s: &str) -> String {
    let mut out = String::from('"');
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn union(values: &[&str]) -> String {
    values.iter().map(|v| quote(v)).collect::<Vec<_>>().join(" | ")
}

/// The generated TypeScript source.
pub fn typescript() -> String {
    let mut ts = String::new();
    let w = &mut ts;
    let _ = writeln!(w, "// GENERATED by crates/euc-telemetry (cargo run -p euc-telemetry --example gen_ts).");
    let _ = writeln!(w, "// Do not edit by hand; change the Rust schema and regenerate.");
    let _ = writeln!(w);
    let _ = writeln!(w, "/** \"EUCT\" read as a little-endian u32. */");
    let _ = writeln!(w, "export const BATCH_MAGIC = 0x{:08x};", u32::from_le_bytes(MAGIC));
    let _ = writeln!(w, "export const BATCH_VERSION = {VERSION};");
    let _ = writeln!(w, "export const BATCH_HEADER_BYTES = {HEADER_BYTES};");
    let _ = writeln!(w, "export const BATCH_FLAG_POSES = {FLAG_POSES};");
    let _ = writeln!(w, "export const POSE_FLOATS = {POSE_FLOATS};");
    let _ = writeln!(w);

    let keys: Vec<&str> = CHANNELS.iter().map(|s| s.key).collect();
    let _ = writeln!(w, "export type ChannelKey = {};", union(&keys));
    let _ = writeln!(w, "export type RateClass = \"fast\" | \"slow\";");
    let _ = writeln!(w);
    let _ = writeln!(w, "export interface ChannelSpec {{");
    let _ = writeln!(w, "  id: number;");
    let _ = writeln!(w, "  key: ChannelKey;");
    let _ = writeln!(w, "  label: string;");
    let _ = writeln!(w, "  unit: string;");
    let _ = writeln!(w, "  rate: RateClass;");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    let _ = writeln!(w, "/** Every channel; the index is the channel id and the column in a batch. */");
    let _ = writeln!(w, "export const CHANNELS: readonly ChannelSpec[] = [");
    for s in &CHANNELS {
        let rate = match s.rate {
            RateClass::Fast => "fast",
            RateClass::Slow => "slow",
        };
        let _ = writeln!(
            w,
            "  {{ id: {}, key: {}, label: {}, unit: {}, rate: {} }},",
            s.id,
            quote(s.key),
            quote(s.label),
            quote(s.unit),
            quote(rate)
        );
    }
    let _ = writeln!(w, "];");
    let _ = writeln!(w);
    let _ = writeln!(w, "/** Channel id by key. */");
    let _ = writeln!(w, "export const CH = {{");
    for s in &CHANNELS {
        let _ = writeln!(w, "  {}: {},", s.key, s.id);
    }
    let _ = writeln!(w, "}} as const satisfies Record<ChannelKey, number>;");
    let _ = writeln!(w);

    let _ = writeln!(
        w,
        "export type EventKind = {};",
        union(&["alarm", "cutoff", "tiltback", "command", "firmware", "scenario", "fault"])
    );
    let _ = writeln!(w);
    let _ = writeln!(w, "export interface TelemetryEvent {{");
    let _ = writeln!(w, "  t_s: number;");
    let _ = writeln!(w, "  kind: EventKind;");
    let _ = writeln!(w, "  text: string;");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    let _ = writeln!(w, "export type BodyRole = {};", union(&["wheel", "shell", "rider", "other"]));
    let _ = writeln!(w, "export type GeomKind = {};", union(&["capsule", "box", "sphere", "cylinder", "ellipsoid"]));
    let _ = writeln!(w);
    let _ = writeln!(w, "/** Geometry in the body frame; MJCF sizes. */");
    let _ = writeln!(w, "export interface Geom {{");
    let _ = writeln!(w, "  kind: GeomKind;");
    let _ = writeln!(w, "  size: [number, number, number];");
    let _ = writeln!(w, "  pos: [number, number, number];");
    let _ = writeln!(w, "  /** [w, x, y, z] */");
    let _ = writeln!(w, "  quat: [number, number, number, number];");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    let _ = writeln!(w, "/** A body the simulator moves; batches carry its pose in this order (world frame, z up). */");
    let _ = writeln!(w, "export interface BodyInfo {{");
    let _ = writeln!(w, "  name: string;");
    let _ = writeln!(w, "  role: BodyRole;");
    let _ = writeln!(w, "  geoms: Geom[];");
    let _ = writeln!(w, "}}");
    let _ = writeln!(w);
    let _ = writeln!(w, "/** What the wheel shows and sounds, as the firmware drives it. */");
    let _ = writeln!(w, "export interface Outputs {{");
    let _ = writeln!(w, "  /** Display driver grid memory, one byte per grid, one bit per segment. */");
    let _ = writeln!(w, "  display_grid: number[];");
    let _ = writeln!(w, "  display_on: boolean;");
    let _ = writeln!(w, "  /** 0..7 */");
    let _ = writeln!(w, "  display_brightness: number;");
    let _ = writeln!(w, "  /** [r, g, b] per LED, strip order. */");
    let _ = writeln!(w, "  leds: [number, number, number][];");
    let _ = writeln!(w, "  /** 0 when silent. */");
    let _ = writeln!(w, "  buzzer_hz: number;");
    let _ = writeln!(w, "}}");
    ts
}

#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    #[test]
    fn committed_typescript_is_current() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..").join(TS_PATH);
        let committed = std::fs::read_to_string(&path).unwrap_or_default();
        assert!(
            committed == typescript(),
            "{} is stale: run `cargo run -p euc-telemetry --example gen_ts`",
            path.display()
        );
    }

    #[test]
    fn magic_matches_the_bytes() {
        assert!(typescript().contains("BATCH_MAGIC = 0x54435545"));
    }
}
