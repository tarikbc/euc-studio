#!/usr/bin/env python3
"""Writes profiles/begode-extreme/probes.toml: where our firmware keeps the quantities the simulator reads.

The stock map (profiles/<wheel>/stockmap.toml) names RAM variables of the stock build by address. Our firmware
moves between builds, so a probe names an ELF symbol and a byte offset into it. This script takes the offsets
and sizes from the target compiler itself: it compiles offsetof() and sizeof() of each member of `struct app`
to assembly and reads the numbers back, so the file always matches the code. A probe uses the stock map's
name when it holds the same quantity, so `euc sim compare` pairs the two firmwares' values.

usage: gen_probes.py --cc ARM_GCC [--check]
  --check   fail (exit 1) when the file is out of date instead of writing it; the image build runs this
"""

import argparse
import os
import re
import subprocess
import sys
import tempfile

FIRMWARE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
WHEEL = "begode-extreme"
OUT = os.path.join(os.path.dirname(FIRMWARE), "profiles", WHEEL, "probes.toml")
INCLUDES = ["core/include", "ports/stm32f1/include", "boards/" + WHEEL, "apps/" + WHEEL, "config"]

# (name, member of struct app, kind, role, note). Names from stockmap.toml where the quantity is the same.
PROBES = [
    ("telemetry_pause", "commands.telemetry_holdoff_groups", "u8", None,
     "telemetry groups still to skip after a received byte"),
    ("alerts", "alarms.alerts", "u8", None, "frame 04 byte 14; bit 2 = IMU fault, bit 6 = hall error"),
    ("speed_cms", "balance.speed_cm_per_s", "s16", None, "the balance's speed estimate, cm/s, forward positive"),
    ("vq_active", "motor.vq_active", "s16", None, "the q voltage the FOC applies; 0 while the stop brake holds"),
    ("pwm_alarm", "alarm_out.pwm_alarm", "u8", None, "PWM above the 'W' 'P' threshold"),
    ("tiltback_speed_deg", "balance.tiltback_speed_deg", "f32", None, "speed tiltback offset, degrees"),
    ("tiltback_battery_deg", "balance.tiltback_battery_deg", "f32", None,
     "battery voltage and temperature tiltback offset, degrees"),
    ("tiltback_pwm_deg", "balance.tiltback_pwm_deg", "f32", None, "PWM tiltback offset, degrees"),
    ("drive_command", "balance.motor_command", "f32", None, "balance command to the FOC, +-1050"),
    ("balance_disabled", "balance.motor_disabled", "u8", "cutoff",
     "1 while the balance output is disabled (fall detectors, handle cut, lock); the output ramps to 0"),
    ("drive_fault", "motor.hard_cut", "u8", "cutoff", "hard cut: bridge off until a power cycle"),
    ("hall_fault", "motor.hall.fault", "u8", "cutoff", "hall fault latched: bridge off until a power cycle"),
    # Our own names: quantities the stock map does not name.
    ("pitch_deg", "balance_out.pitch_deg", "f32", None, "the balance's pitch, degrees"),
    ("roll_deg", "balance_out.roll_deg", "f32", None, "the balance's roll, degrees"),
    ("hall_line_fault", "motor.hall.line_fault", "u8", None,
     "clean: one hall line found stuck; the state is rebuilt from the other two"),
]

SIZES = {"u8": 1, "s8": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4}

HEADER = """\
# Begode Extreme: named places in OUR firmware (firmware/), for euc sim compare, viewers and
# scenario checks. Read by crates/euc-sim (probes.rs).
#
# GENERATED by firmware/tools/gen_probes.py from offsetof() in struct app (apps/begode-extreme/app.h); do not
# edit. Change the PROBES list in the script, then run:
#   cmake --build --preset target-clean --target probes
# The image build checks that this file matches the code.
#
# Each variable names an ELF symbol and a byte offset into it; the simulator resolves them against the image's
# .elf (next to the .bin). A probe uses the stock map's name (stockmap.toml) when it holds the same quantity.

schema = 1
"""


def measure(cc):
    lines = ["#include <stddef.h>", '#include "app.h"']
    for i, (_, member, _, _, _) in enumerate(PROBES):
        lines.append("const unsigned probe_offset_%d = offsetof(struct app, %s);" % (i, member))
        lines.append("const unsigned probe_size_%d = sizeof(((struct app *)0)->%s);" % (i, member))
    with tempfile.TemporaryDirectory() as tmp:
        source = os.path.join(tmp, "probes.c")
        with open(source, "w") as f:
            f.write("\n".join(lines) + "\n")
        command = [cc, "-std=c11", "-mcpu=cortex-m3", "-mthumb", "-DEUC_PROFILE_CLEAN=1", "-S", "-o", "-"]
        command += ["-I" + os.path.join(FIRMWARE, d) for d in INCLUDES]
        command.append(source)
        asm = subprocess.run(command, check=True, capture_output=True, text=True).stdout
    values = dict(re.findall(r"^(probe_\w+):\s*\n\s*\.word\s+(\d+)", asm, re.M))
    result = []
    for i in range(len(PROBES)):
        result.append((int(values["probe_offset_%d" % i]), int(values["probe_size_%d" % i])))
    return result


def render(measured):
    out = [HEADER]
    for (name, member, kind, role, note), (offset, size) in zip(PROBES, measured):
        if SIZES[kind] != size:
            sys.exit("gen_probes: %s (app.%s) is %d bytes, kind %s wants %d" % (name, member, size, kind, SIZES[kind]))
        out.append("[[var]]")
        out.append('name = "%s"' % name)
        out.append('symbol = "app"')
        out.append("offset = %d  # app.%s" % (offset, member))
        out.append("size = %d" % size)
        out.append('kind = "%s"' % kind)
        if role:
            out.append('role = "%s"' % role)
        out.append('note = "%s"' % note)
        out.append("")
    return "\n".join(out)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cc", required=True, help="the target C compiler (arm-none-eabi-gcc)")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = render(measure(args.cc))
    current = open(OUT).read() if os.path.exists(OUT) else ""
    if args.check:
        if current != text:
            sys.exit("gen_probes: %s is out of date; run: cmake --build --preset target-clean --target probes" % OUT)
        return
    if current != text:
        with open(OUT, "w") as f:
            f.write(text)
        print("wrote", os.path.relpath(OUT, os.path.dirname(FIRMWARE)))


if __name__ == "__main__":
    main()
