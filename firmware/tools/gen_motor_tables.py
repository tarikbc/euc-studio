#!/usr/bin/env python3
"""Writes the FOC lookup tables (quarter-wave sine, circle limitation) as a C source file.

Usage:
    gen_motor_tables.py <output.c>

The build runs this for every configuration (core/CMakeLists.txt), so the tables are computed from their
formulas and no table data is kept in the source tree. tests/unit/test_foc.c checks the result against the
documented values. Python 3.11+ standard library only.

Quarter-wave sine
    S[i] = round(32767 sin(i pi / 512)), i = 0..255: one quadrant in 256 steps, Q1.15.

Circle limitation
    Entry k scales a voltage vector (Vq, Vd) whose squared length lies in [(62 + k), (63 + k)) x 2^24 back to
    at most 99 % of full scale (32439). The table of the stock drive (the "99 % modulation" table of a common
    FOC design) is not one smooth curve: from entry 13 to 14 and from 39 to 40 it advances half a step. With
    that step pattern it follows
        M[k] = round(A / sqrt(B + k - h(k) / 2)),  A = 256971.27,  B = 62.001,
    where h(k) is the number of half steps at or before entry k. A and B are fitted: they reproduce every
    stock entry with a rounding margin of more than 0.01. Every entry keeps the scaled vector inside the
    99 % circle (checked below and in the unit test).
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

SINE_ENTRIES = 256
SINE_SCALE = 32767

CIRCLE_ENTRIES = 66
CIRCLE_MAX_MODULE = 32439
CIRCLE_FIRST_BIN = 62
CIRCLE_SCALE = 256971.27
CIRCLE_OFFSET = 62.001
CIRCLE_HALF_STEPS = (14, 40)

# A value this close to .5 could round differently on another libm; the generator refuses it.
MIN_ROUNDING_MARGIN = 1e-6


def round_half_up(value: float) -> int:
    fraction = value - math.floor(value)
    if abs(fraction - 0.5) < MIN_ROUNDING_MARGIN:
        raise SystemExit(f"gen_motor_tables: {value!r} is too close to a rounding boundary")
    return math.floor(value + 0.5)


def sine_table() -> list[int]:
    return [round_half_up(SINE_SCALE * math.sin(i * math.pi / (2 * SINE_ENTRIES))) for i in range(SINE_ENTRIES)]


def circle_table() -> list[int]:
    table = []
    for k in range(CIRCLE_ENTRIES):
        half_steps = sum(1 for step in CIRCLE_HALF_STEPS if k >= step)
        table.append(round_half_up(CIRCLE_SCALE / math.sqrt(CIRCLE_OFFSET + k - half_steps / 2)))
    for k, factor in enumerate(table):
        # Largest squared length in bin k, scaled by the entry (Q1.15), must stay inside the 99 % circle.
        if factor * factor * (CIRCLE_FIRST_BIN + k + 1) * 2**24 > CIRCLE_MAX_MODULE**2 * 2**30:
            raise SystemExit(f"gen_motor_tables: circle entry {k} leaves the 99 % circle")
    return table


def c_array(c_type: str, name: str, size_macro: str, values: list[int]) -> str:
    rows = []
    for start in range(0, len(values), 10):
        rows.append("    " + ", ".join(str(v) for v in values[start : start + 10]) + ",")
    return f"const {c_type} {name}[{size_macro}] = {{\n" + "\n".join(rows) + "\n};\n"


def render() -> str:
    return (
        "/* Generated by firmware/tools/gen_motor_tables.py. Do not edit. */\n"
        '#include "euc/motor/foc_math.h"\n'
        "\n"
        + c_array("int16_t", "euc_foc_sine_table", "EUC_FOC_SINE_ENTRIES", sine_table())
        + "\n"
        + c_array("uint16_t", "euc_foc_circle_table", "EUC_FOC_CIRCLE_ENTRIES", circle_table())
    )


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    output = Path(sys.argv[1])
    output.parent.mkdir(parents=True, exist_ok=True)
    text = render()
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
